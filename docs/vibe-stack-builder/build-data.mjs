// Generate data.js for the public web demo from the canonical capability cards.
// Single source of truth: /capabilities/*.json. Do not hand-edit data.js.
// Run: node docs/vibe-stack-builder/build-data.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const capDir = join(here, '..', '..', 'capabilities');

function toTool(card) {
  return {
    id: card.id,
    title: card.title || card.id,
    family: card.family || 'general',
    goal: card.goal || '',
    whenToUse: card.when_to_use || [],
    whenNotToUse: card.when_not_to_use || [],
    risks: card.risks || [],
    primaryTools: (card.primary_tools || []).map((t) => ({
      name: t.name,
      url: t.url,
      license: t.license,
      role: t.role,
    })),
    searchTerms: card.search_terms || [],
    codexPrompt: card.codex_prompt || '',
    verification: card.verification || [],
    sources: card.sources || [],
    level: card.level ?? null,
    status: card.status || null,
  };
}

const files = readdirSync(capDir)
  .filter((f) => f.endsWith('.json'))
  .sort();

const tools = {};
for (const f of files) {
  const card = JSON.parse(readFileSync(join(capDir, f), 'utf8'));
  if (!card || !card.id) continue;
  tools[card.id] = toTool(card);
}

const banner =
  '// GENERATED by build-data.mjs from /capabilities/*.json - do not edit by hand.\n' +
  '// Regenerate: node docs/vibe-stack-builder/build-data.mjs\n';
const body =
  'window.VBT = window.VBT || {};\n' +
  'window.VBT.tools = ' +
  JSON.stringify(tools, null, 2) +
  ';\n';

writeFileSync(join(here, 'data.js'), banner + body);
console.log(`Wrote data.js with ${Object.keys(tools).length} tools: ${Object.keys(tools).join(', ')}`);
